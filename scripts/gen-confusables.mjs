#!/usr/bin/env node
// scripts/gen-confusables.mjs — regenerate ../confusables.mjs from Unicode's TR39 confusables.txt.
//
//   node scripts/gen-confusables.mjs [path/to/confusables.txt]   # write confusables.mjs
//   node scripts/gen-confusables.mjs --check [path]               # exit 1 if the committed file differs
//
// With no path, the pinned file is downloaded from unicode.org. Either way its SHA-256 MUST equal
// SOURCE_SHA256 below, or the generator refuses: the vendored table is only as trustworthy as its
// pinned input, and the bundle must be reproducible from it byte-for-byte.
//
// The Unicode version is pinned to 16.0.0 to match the ICU data in Node 20/22 (process.versions.unicode
// === "16.0"), so the NFKC/NFD steps of skeleton() and the confusables mapping agree on one version.
// To move versions: bump UNICODE_VERSION, set SOURCE_SHA256 to the new file's hash, re-run, commit both.

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

export const UNICODE_VERSION = "16.0.0";
export const SOURCE_URL = `https://www.unicode.org/Public/security/${UNICODE_VERSION}/confusables.txt`;
export const SOURCE_SHA256 = "95bd0aad6dced5ebc63436f459c06ab21a8d107cd842fb57f5c3a1e91bca8611";

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = join(HERE, "..", "confusables.mjs");

const args = process.argv.slice(2);
const check = args.includes("--check");
const srcPath = args.find((a) => !a.startsWith("--"));

let raw;
if (srcPath) raw = readFileSync(srcPath);
else {
  const res = await fetch(SOURCE_URL);
  if (!res.ok) throw new Error(`download ${SOURCE_URL} -> HTTP ${res.status}`);
  raw = Buffer.from(await res.arrayBuffer());
}
const sha = createHash("sha256").update(raw).digest("hex");
if (sha !== SOURCE_SHA256) {
  console.error(`refusing: confusables.txt SHA-256 ${sha} != pinned ${SOURCE_SHA256} (Unicode ${UNICODE_VERSION})`);
  process.exit(2);
}

// Each data line: <source cp> ; <target cps, space-separated> ; <type> # comment
const entries = [];
for (const line of raw.toString("utf8").replace(/^\uFEFF/, "").split(/\r?\n/)) {
  const body = line.split("#")[0].trim();
  if (!body) continue;
  const [src, dst] = body.split(";").map((f) => f.trim());
  if (!/^[0-9A-F]{4,6}$/.test(src) || !/^[0-9A-F]{4,6}( [0-9A-F]{4,6})*$/.test(dst)) throw new Error(`unparseable line: ${line}`);
  entries.push([parseInt(src, 16), dst.split(" ").map((h) => parseInt(h, 16))]);
}
entries.sort((a, b) => a[0] - b[0]);
for (let i = 1; i < entries.length; i++) if (entries[i][0] === entries[i - 1][0]) throw new Error(`duplicate source U+${entries[i][0].toString(16)}`);

// Compact, ASCII-only encoding (no literal confusable/invisible chars in the source):
// "src:dst1.dst2,src:dst,..." with code points in lowercase hex.
const data = entries.map(([s, d]) => `${s.toString(16)}:${d.map((c) => c.toString(16)).join(".")}`).join(",");
const chunks = data.match(/.{1,100}(,|$)/g);

const out = `// confusables.mjs — GENERATED by scripts/gen-confusables.mjs. DO NOT EDIT BY HAND.
// Unicode TR39 confusables (prototype mapping for skeleton()), Unicode ${UNICODE_VERSION}.
// Source: ${SOURCE_URL}
// Source SHA-256: ${SOURCE_SHA256}
// Entries: ${entries.length}
export const CONFUSABLES_UNICODE_VERSION = ${JSON.stringify(UNICODE_VERSION)};
export const CONFUSABLES_SOURCE_SHA256 = ${JSON.stringify(SOURCE_SHA256)};
const DATA =
${chunks.map((c) => "  " + JSON.stringify(c)).join(" +\n")};
/** code point → prototype string */
export const CONFUSABLES = new Map(DATA.split(",").map((e) => {
  const [s, d] = e.split(":");
  return [parseInt(s, 16), String.fromCodePoint(...d.split(".").map((h) => parseInt(h, 16)))];
}));
`;

if (check) {
  let cur = ""; try { cur = readFileSync(OUT, "utf8"); } catch {}
  if (cur !== out) { console.error("confusables.mjs is stale or hand-edited — re-run scripts/gen-confusables.mjs"); process.exit(1); }
  console.log(`confusables.mjs up to date (${entries.length} entries, Unicode ${UNICODE_VERSION})`);
} else {
  writeFileSync(OUT, out);
  console.log(`wrote ${OUT}: ${entries.length} entries from Unicode ${UNICODE_VERSION} (sha256 ${sha})`);
}
